"""Plot results from an EnKF.oda run.

Reads enkf_results.py (generated by OpenDA's PythonResultWriter) and produces:
  1. Time series of ensemble-mean forecast vs analysis vs observations at
     0 m, 10 m, 20 m.
  2. (Optional) Depth profiles of x_f_central vs x_a_central at selected
     analysis times, showing the EnKF correction along the full water column.

Run this script after:  od.bat EnKF.oda
"""

import os
import sys
from datetime import datetime as _dt, timedelta as _td

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.lines as mlines
import matplotlib.dates as mdates

# ── path resolution ───────────────────────────────────────────────────────────
_here = globals().get("__file__", None)
if _here is not None:
    SCRIPT_DIR = os.path.dirname(os.path.abspath(_here))
    ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
else:
    _cwd = os.getcwd()
    ROOT = _cwd
    while ROOT and not os.path.isdir(os.path.join(ROOT, "snapshot")):
        _parent = os.path.dirname(ROOT)
        if _parent == ROOT:
            raise RuntimeError("Cannot locate project root (snapshot/ not found)")
        ROOT = _parent
    SCRIPT_DIR = os.path.join(ROOT, "testing_simple", "exercise_simstrat")

sys.path.insert(0, os.path.join(ROOT, "snapshot"))
from snapshot_io import read_snapshot

RESULTS_FILE  = os.path.join(SCRIPT_DIR, "enkf_results.py")
SNAPSHOT_PATH = os.path.join(SCRIPT_DIR, "stochModel", "template", "Results",
                              "simulation-snapshot.dat")
PAR_PATH      = os.path.join(SCRIPT_DIR, "stochModel", "template", "Settings.par")
REF_DATE      = pd.Timestamp("1981-01-01", tz="UTC")

OBS_DEPTHS  = [0, 10, 20]
OBS_COLORS  = ["#e41a1c", "#ff7f00", "#4daf4a"]
DEPTH_LABELS = ["0 m", "10 m", "20 m"]

# ── load results ──────────────────────────────────────────────────────────────
print(f"Loading {RESULTS_FILE} ...")
_ns = {}
with open(RESULTS_FILE) as _f:
    exec(_f.read(), _ns)

analysis_time   = np.array(_ns["analysis_time"]).ravel()  # (n_steps,)
pred_f_central  = np.array(_ns["pred_f_central"])        # (n_steps, 3)
pred_a_central  = np.array(_ns["pred_a_central"])        # (n_steps, 3)
obs             = np.array(_ns["obs"])                   # (n_steps, 3)

dates = REF_DATE + pd.to_timedelta(analysis_time, unit="D")

# Optional full-state profiles
x_f_central = np.array(_ns["x_f_central"]) if "x_f_central" in _ns else None
x_a_central = np.array(_ns["x_a_central"]) if "x_a_central" in _ns else None

print(f"  {len(analysis_time)} analysis steps")
print(f"  Full state profiles available: {x_f_central is not None}")

# ── depth axis from template snapshot ─────────────────────────────────────────
snap = read_snapshot(SNAPSHOT_PATH, par_path=PAR_PATH)
T_template = snap.model["T"]
z_vol      = snap.grid["z_volume"][-len(T_template):]
lake_lev   = snap.grid["lake_level"]
depth_axis = lake_lev - z_vol           # positive downward (m)
order      = np.argsort(depth_axis)
depth_axis = depth_axis[order]

# extract analysis state at observation depths from x_a_central directly
# (pred_a_central from OpenDA is H·x_f, not H·x_a — use state vector instead)
_obs_cols = [int(np.argmin(np.abs(lake_lev - z_vol - d))) for d in OBS_DEPTHS]
if x_a_central is not None:
    x_a_at_obs = np.column_stack([x_a_central[:, c] for c in _obs_cols])
else:
    x_a_at_obs = pred_a_central

# ── Figure 1: time series at 3 depths ─────────────────────────────────────────
fig, axes = plt.subplots(3, 1, figsize=(12, 9), sharex=True)

for i, (ax, label, color) in enumerate(zip(axes, DEPTH_LABELS, OBS_COLORS)):
    ax.fill_between(dates, pred_f_central[:, i], x_a_at_obs[:, i],
                    alpha=0.25, color=color, label="analysis correction")
    ax.plot(dates, pred_f_central[:, i], color=color, lw=1.5,
            ls="--", label=f"forecast {label}")
    ax.plot(dates, x_a_at_obs[:, i], color=color, lw=2,
            label=f"analysis {label}")
    ax.scatter(dates, obs[:, i], color="black", s=12, zorder=5,
               label="obs")
    ax.set_ylabel("T (°C)")
    ax.set_title(f"Depth {label}")
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(True, alpha=0.3)

axes[-1].set_xlabel("Date")
fig.suptitle("EnKF — forecast vs analysis vs observations", fontsize=12)
plt.tight_layout()
out1 = os.path.join(SCRIPT_DIR, "enkf_timeseries.png")
plt.savefig(out1, dpi=150)
print(f"Saved: {out1}")

# ── Figure 1b: Jan 5 zoom ─────────────────────────────────────────────────────
zoom_year  = dates[0].year
zoom_start = pd.Timestamp(zoom_year, 1, 4, tz="UTC")
zoom_end   = pd.Timestamp(zoom_year, 1, 7, tz="UTC")

fig1b, axes1b = plt.subplots(3, 1, figsize=(12, 9), sharex=True)
for i, (ax, label, color) in enumerate(zip(axes1b, DEPTH_LABELS, OBS_COLORS)):
    ax.fill_between(dates, pred_f_central[:, i], x_a_at_obs[:, i],
                    alpha=0.25, color=color, label="analysis correction")
    ax.plot(dates, pred_f_central[:, i], color=color, lw=1.5,
            ls="--", label=f"forecast {label}")
    ax.plot(dates, x_a_at_obs[:, i], color=color, lw=2,
            label=f"analysis {label}")
    ax.scatter(dates, obs[:, i], color="black", s=12, zorder=5, label="obs")
    ax.set_ylabel("T (°C)")
    ax.set_title(f"Depth {label}")
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(True, alpha=0.3)
    ax.set_xlim(zoom_start, zoom_end)

axes1b[-1].set_xlabel("Date")
fig1b.suptitle("EnKF — forecast vs analysis vs observations (Jan 5 zoom)", fontsize=12)
plt.tight_layout()
out1b = os.path.join(SCRIPT_DIR, "enkf_timeseries_jan5_zoom.png")
fig1b.savefig(out1b, dpi=150)
print(f"Saved: {out1b}")

# ── Figure 1c: Jan 25–29 zoom ─────────────────────────────────────────────────
zoom2_start = pd.Timestamp(zoom_year, 1, 25, tz="UTC")
zoom2_end   = pd.Timestamp(zoom_year, 1, 30, tz="UTC")
_mask = (dates >= zoom2_start) & (dates <= zoom2_end)

fig1c, axes1c = plt.subplots(3, 1, figsize=(12, 9), sharex=True)
for i, (ax, label, color) in enumerate(zip(axes1c, DEPTH_LABELS, OBS_COLORS)):
    ax.fill_between(dates, pred_f_central[:, i], x_a_at_obs[:, i],
                    alpha=0.25, color=color, label="analysis correction")
    ax.plot(dates, pred_f_central[:, i], color=color, lw=1.5,
            ls="--", label=f"forecast {label}")
    ax.plot(dates, x_a_at_obs[:, i], color=color, lw=2,
            label=f"analysis {label}")
    ax.scatter(dates, obs[:, i], color="black", s=12, zorder=5, label="obs")
    ax.set_ylabel("T (°C)")
    ax.set_title(f"Depth {label}")
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(True, alpha=0.3)
    ax.set_xlim(zoom2_start, zoom2_end)
    _vals = np.concatenate([pred_f_central[_mask, i], pred_a_central[_mask, i], obs[_mask, i]])
    if _vals.size:
        _span = _vals.max() - _vals.min()
        _margin = _span * 0.15 if _span > 0 else 0.1
        ax.set_ylim(_vals.min() - _margin, _vals.max() + _margin)

axes1c[-1].set_xlabel("Date")
fig1c.suptitle("EnKF — forecast vs analysis vs observations (Jan 25–29 zoom)", fontsize=12)
plt.tight_layout()
out1c = os.path.join(SCRIPT_DIR, "enkf_timeseries_jan25_zoom.png")
fig1c.savefig(out1c, dpi=150)
print(f"Saved: {out1c}")

# ── Figure: individual ensemble members ──────────────────────────────────────
def _read_t_out(path):
    with open(path) as fh:
        header, *data_lines = fh.readlines()
    z_cols = np.array([float(v) for v in header.strip().split(',')[1:]])
    times, rows = [], []
    for line in data_lines:
        parts = line.strip().split(',')
        if not parts or not parts[0]:
            continue
        times.append(_dt(1981, 1, 1) + _td(days=float(parts[0])))
        rows.append([float(x) for x in parts[1:]])
    return times, z_cols, np.array(rows)

_work_base  = os.path.join(SCRIPT_DIR, "work_enkf")
_ens_paths  = [os.path.join(_work_base, f"work{i}", "Results", "T_out.dat") for i in range(1, 6)]
_ens_data   = [_read_t_out(p) for p in _ens_paths]

_t0, _z_cols, _ = _ens_data[0]
_depth_fs = lake_lev - _z_cols   # positive depth from surface, matches existing depth_axis

def _nc(arr, t):
    return int(np.argmin(np.abs(arr - t)))

_col_0  = _nc(_depth_fs, 0.0)
_col_10 = _nc(_depth_fs, 10.0)
_col_20 = _nc(_depth_fs, 20.0)

_dates_naive = [_dt(1981, 1, 1) + _td(days=float(t)) for t in analysis_time]
_ens_colors  = plt.cm.tab10.colors[:5]

fig_ens, axes_ens = plt.subplots(3, 1, figsize=(12, 9), sharex=True)
fig_ens.suptitle("EnKF — individual ensemble members at observed depths", fontsize=12)

for ax, col, obs_idx, label in [
    (axes_ens[0], _col_0,  0, "0 m"),
    (axes_ens[1], _col_10, 1, "10 m"),
    (axes_ens[2], _col_20, 2, "20 m"),
]:
    for k, (t_ens, _, T_ens) in enumerate(_ens_data):
        ax.plot(t_ens, T_ens[:, col], lw=0.9, alpha=0.8, color=_ens_colors[k],
                label=f"member {k + 1}")
    ax.scatter(_dates_naive, obs[:, obs_idx], color="black", s=20, zorder=5, label="obs")
    ax.set_ylabel("T (°C)")
    ax.set_title(f"Depth {label}")
    ax.legend(fontsize=8, loc="upper right")
    ax.grid(True, alpha=0.3)

axes_ens[-1].set_xlabel("Date")
axes_ens[-1].xaxis.set_major_formatter(mdates.DateFormatter('%Y-%m-%d'))
fig_ens.autofmt_xdate()
plt.tight_layout()
out_ens = os.path.join(SCRIPT_DIR, "enkf_ensemble_members.png")
fig_ens.savefig(out_ens, dpi=150)
print(f"Saved: {out_ens}")

# ── Figure 2: depth profiles of EnKF correction ───────────────────────────────
if x_f_central is not None and x_a_central is not None:
    n_profile_steps = min(6, len(analysis_time))
    step_idxs = np.linspace(0, len(analysis_time) - 1, n_profile_steps, dtype=int)

    fig2, axes2 = plt.subplots(1, n_profile_steps, figsize=(3 * n_profile_steps, 8),
                                sharey=True)
    if n_profile_steps == 1:
        axes2 = [axes2]

    for ax, idx in zip(axes2, step_idxs):
        T_f = x_f_central[idx][order]
        T_a = x_a_central[idx][order]
        ax.plot(T_f, depth_axis, color="steelblue", lw=2, ls="--", label="forecast")
        ax.plot(T_a, depth_axis, color="tomato",    lw=2,           label="analysis")
        ax.fill_betweenx(depth_axis, T_f, T_a, alpha=0.2, color="tomato")
        ax.scatter(obs[idx], OBS_DEPTHS, color="black", s=30, zorder=6,
                   label="obs" if ax is axes2[0] else None)
        date_str = dates[idx].strftime("%d %b")
        ax.set_title(date_str, fontsize=9)
        ax.set_xlabel("T (°C)")
        ax.invert_yaxis()
        ax.grid(True, alpha=0.3)
        if ax is axes2[0]:
            ax.set_ylabel("Depth (m)")
            ax.legend(fontsize=8)

    fig2.suptitle("EnKF — depth profiles: forecast vs analysis", fontsize=11)
    plt.tight_layout()
    out2 = os.path.join(SCRIPT_DIR, "enkf_profiles.png")
    plt.savefig(out2, dpi=150)
    print(f"Saved: {out2}")

plt.show()
print("Done.")
